     * مصرف‌کننده‌اش `StorePageRequest`/`UpdatePageRequest` است نه `rulesFor()`.
     *
     * @return array<string, array<int, mixed>>
     */
    public static function pageStyleRules(string $required = 'nullable', string $key = Page::STYLE): array
    {
        $rules = [$key => [$required, 'array']];

        foreach (self::PAGE_STYLE_SLOTS as $slot => $spec) {
            $rules[$key.'.'.$slot] = ['nullable', 'string', Rule::in($spec['values'])];
        }

        return $rules;
    }

    private const GLASS_VARIANTS = ['clear', 'light', 'dark', 'control'];

    private const GLASS_COLOR_FIELDS = ['fill', 'rimSide', 'rimFlat', 'shade', 'sheen'];

    private const GLASS_NUMBER_FIELDS = ['frost', 'depth', 'lightAngle', 'radius'];

    /**
     * پیش از این، `data.glass` فقط `['nullable', 'array']` بود — بدونِ قاعده‌ی
     * فرزند، لاراول نمی‌تواند کلیدِ ناشناخته را از آرایه حذف کند
     * (`excludeUnvalidatedArrayKeys`)، پس هر JSONای که ادمین می‌فرستاد
     * دقیقاً همان‌طور ذخیره می‌شد.
     */
    private function glassRules(string $key, string $required): array
    {
        $rules = [
            $key => [$required, 'array'],
            $key.'.variant' => ['nullable', 'string', Rule::in(self::GLASS_VARIANTS)],
        ];

        foreach (self::GLASS_COLOR_FIELDS as $field) {
            $rules[$key.'.'.$field] = ['nullable', 'string', 'max:255'];
        }

        foreach (self::GLASS_NUMBER_FIELDS as $field) {
            $rules[$key.'.'.$field] = ['nullable', 'numeric'];
        }

        return $rules;
    }

    /**
     * قواعدِ ویجتِ `style` — فقط برای اسلات‌هایی که **همین نوعِ بلوک** اعلام کرده.
     *
     * اسلاتی که اعلام نشده هیچ قاعده‌ای نمی‌گیرد، پس
     * `excludeUnvalidatedArrayKeys` بی‌صدا حذفش می‌کند — همان رفتارِ `glass`،
     * و همان چیزی که می‌خواهیم: دادهٔ بی‌مصرف ذخیره نمی‌شود.
     *
     * نبودِ `slots` خطای برنامه‌نویس است نه ورودیِ کاربر، پس مثلِ
     * `selectOptions()` با استثنا متوقف می‌شود — نه با `Rule::in([])` که
     * خاموش **هر** مقداری را رد می‌کند و شبیهِ باگِ داده به‌نظر می‌رسد.
     *
     * @param  array<string, mixed>  $field
     * @return array<string, list<mixed>>
     */
    private function styleRules(string $key, array $field, string $required, string $context): array
    {
        $slots = $field['slots'] ?? [];

        if (empty($slots)) {
            throw new \InvalidArgumentException(
                "فیلدِ style با نامِ «{$context}» هیچ اسلاتی (slots) اعلام نکرده — این خطای برنامه‌نویس است."
            );
        }

        $rules = [$key => [$required, 'array']];

        foreach ($slots as $slot) {
            if (! isset(self::STYLE_SLOTS[$slot])) {
                throw new \InvalidArgumentException(
                    "اسلاتِ ناشناخته‌ی «{$slot}» در «{$context}» — واژگانِ مجاز در STYLE_SLOTS است."
                );
            }

            $rules[$key.'.'.$slot] = ['nullable', 'string', Rule::in(self::STYLE_SLOTS[$slot]['values'])];
        }

        return $rules;
    }

    /**
     * گزینه‌های یک فیلدِ select را برمی‌گرداند؛ نبودنشان خطای برنامه‌نویس است،
     * نه ورودیِ کاربر — پس با استثنا متوقف می‌شود، نه با قاعده‌ای که خاموش
     * همه‌چیز را رد می‌کند (`Rule::in(null)`).
     *
     * @param  array<string, mixed>  $field
     * @return list<string>
     */
    private function selectOptions(array $field, string $context): array
    {
        $options = $field['options'] ?? null;

        if (empty($options)) {
            throw new \InvalidArgumentException(
                "فیلدِ select با نامِ «{$context}» گزینه‌ای (options) تعریف نکرده — این خطای برنامه‌نویس است."
            );
        }

        // گزینه‌ها یا فهرستِ رشته‌اند یا فهرستِ `{value,label}` — Rule::in فقط
        // مقدارِ واقعی (value) را می‌خواهد، نه لیبلِ فارسیِ کنارِ آن.
        return array_map(
            static fn ($option) => is_array($option) ? $option['value'] : $option,
            $options
        );
    }
