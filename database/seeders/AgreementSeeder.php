    /** متن کامل توافق‌نامه الیت یار — نسخه ۱.۰ از سند رسمی، با نام‌گذاری «الیت یار». */
    private function eliteYARTermsContent(): string
    {
        return <<<'TEXT'
توافق‌نامه آنلاین همکاری الیت یار (مشاور همراه خرید) در پلتفرم الیت‌زون
مالک پلتفرم: شرکت نرم‌افزاری سازه اسپادانا — نشانی پلتفرم: elitezone.me — نسخه ۱.۰

مقدمه
این توافق‌نامه میان شرکت نرم‌افزاری سازه اسپادانا، مالک و بهره‌بردار پلتفرم الیت‌زون، از یک طرف، و شخص حقیقی یا حقوقی متقاضی فعالیت به‌عنوان «الیت یار (مشاور همراه خرید)» در پلتفرم الیت‌زون، از طرف دیگر، منعقد می‌شود.
متقاضی با تکمیل فرآیند ثبت‌نام، احراز هویت، انتخاب گزینه پذیرش، ورود کد تأیید پیامکی، استفاده از پنل الیت یار یا ادامه فعالیت در پلتفرم، اعلام می‌نماید که مفاد این توافق‌نامه را مطالعه کرده، فهمیده و پذیرفته است.

ماده ۱ — تعاریف
۱-۱. الیت‌زون: منظور از الیت‌زون، پلتفرم آنلاین عرضه، فروش، پیگیری و مدیریت خرید کالاها و خدمات ساختمانی است که توسط شرکت نرم‌افزاری سازه اسپادانا اداره می‌شود.
۱-۲. الیت یار (مشاور همراه خرید): الیت یار شخص حقیقی یا حقوقی مستقلی است که در چارچوب پلتفرم الیت‌زون، نسبت به معرفی، راهنمایی، آماده‌سازی پیش‌سفارش، مقایسه کالا، توضیح مشخصات عمومی کالا، پیگیری سفارش و همراهی کارفرما در فرآیند خرید اقدام می‌کند. الیت یار، طراح، ناظر، مجری، محاسب، آزمایشگاه، کارشناس رسمی، کنترل‌کننده فنی پروژه یا نماینده رسمی الیت‌زون یا تأمین‌کننده محسوب نمی‌شود، مگر آنکه در قرارداد جداگانه‌ای صراحتاً خلاف آن توافق شده باشد.
۱-۳. کارفرما / خریدار نهایی: شخص حقیقی یا حقوقی است که کالا یا خدمات را از الیت‌زون خریداری می‌کند یا خرید برای پروژه وی انجام می‌شود.
۱-۴. پیش‌سفارش: پیشنهاد اولیه خرید است که ممکن است توسط الیت یار، کارفرما یا الیت‌زون در پلتفرم ایجاد شود. پیش‌سفارش تا زمان تأیید نهایی کارفرما یا نماینده احرازشده وی و تعیین تکلیف پرداخت، سفارش قطعی محسوب نمی‌شود.
۱-۵. سفارش قطعی: سفارشی است که مشخصات کالا، مقدار، قیمت، شرایط تحویل، کارفرمای احرازشده، الیت یار مرتبط و وضعیت پرداخت آن در سامانه الیت‌زون ثبت و تأیید شده باشد.
۱-۶. کیف پول الیت یار: دفتر حساب نرم‌افزاری الیت یار در پلتفرم الیت‌زون برای ثبت کارمزدها، پاداش‌ها، کسورات، تعدیلات، درخواست برداشت و سوابق مالی مرتبط با فعالیت الیت یار است. کیف پول الیت یار حساب بانکی مستقل محسوب نمی‌شود و برداشت واقعی از طریق حساب بانکی یا مسیرهای پرداخت مورد قبول الیت‌زون انجام می‌گردد.

ماده ۲ — موضوع توافق‌نامه
موضوع این توافق‌نامه، تنظیم چارچوب همکاری الیت یار با الیت‌زون برای معرفی، راهنمایی، آماده‌سازی و پیگیری خرید کالاها و خدمات ساختمانی در پلتفرم الیت‌زون است.
الیت یار می‌تواند حسب امکانات پلتفرم، کارفرما را به الیت‌زون معرفی کند، برای وی پیش‌سفارش ایجاد نماید، کالاها را در چارچوب اطلاعات موجود در پلتفرم مقایسه کند، لینک تأیید سفارش را برای کارفرما ارسال نماید و وضعیت سفارش را پیگیری کند.
تأیید نهایی خرید، پرداخت، پذیرش شرایط خرید و صدور فاکتور فروش، حسب مورد، باید توسط کارفرما یا نماینده احرازشده وی انجام شود؛ مگر آنکه اختیار مشخص و قابل استناد دیگری در سامانه ثبت شده باشد.

ماده ۳ — ماهیت رابطه طرفین
۳-۱. الیت یار، شخصی مستقل است و پذیرش این توافق‌نامه به هیچ‌وجه موجب ایجاد رابطه استخدامی، کارگری، نمایندگی، وکالت عام، شراکت، عاملیت، کارگزاری رسمی، مسئولیت تضامنی یا رابطه کارفرما و کارگر میان الیت یار و الیت‌زون نمی‌شود.
۳-۲. الیت یار مسئول کلیه تعهدات مالی، مالیاتی، بیمه‌ای، صنفی، حرفه‌ای و قانونی مرتبط با فعالیت خود است.
۳-۳. الیت‌زون هیچ‌گونه تضمینی نسبت به میزان درآمد، تعداد سفارش، استمرار فعالیت، میزان کارمزد یا موفقیت اقتصادی الیت یار ارائه نمی‌کند.
۳-۴. الیت‌زون مجاز است با سایر الیت یاران همکاری کند و الیت یار نیز، با رعایت تعهدات محرمانگی و عدم دور زدن پلتفرم، می‌تواند خارج از الیت‌زون فعالیت حرفه‌ای مستقل داشته باشد.

ماده ۴ — احراز هویت و مدارک الیت یار
۴-۱. الیت یار متعهد است اطلاعات هویتی، تماس، بانکی، مالیاتی، شغلی و حرفه‌ای خود را به‌صورت صحیح، کامل و به‌روز در پلتفرم ثبت کند.
۴-۲. برای اشخاص حقیقی، الیت‌زون می‌تواند اطلاعاتی مانند نام و نام خانوادگی، شماره ملی، تاریخ تولد، شماره موبایل، اطلاعات بانکی، مدارک شغلی، شماره نظام مهندسی یا سایر مدارک لازم را دریافت و بررسی کند.
۴-۳. برای اشخاص حقوقی، الیت‌زون می‌تواند اطلاعات ثبتی، شناسه ملی، اطلاعات نماینده مجاز، مدارک نمایندگی، اطلاعات بانکی و مالیاتی و سایر مدارک لازم را دریافت کند.
۴-۴. در صورت نقص مدارک، عدم تطابق اطلاعات، عدم احراز هویت، تغییر وضعیت حرفه‌ای یا بروز ابهام جدی، الیت‌زون حق دارد ثبت‌نام، فعالیت، پرداخت کارمزد یا برداشت از کیف پول الیت یار را تا رفع مشکل تعلیق کند.

ماده ۵ — فرآیند همکاری الیت یار
۵-۱. الیت یار می‌تواند کارفرما را به استفاده از الیت‌زون دعوت کند و مزایای خرید از پلتفرم را برای او توضیح دهد.
۵-۲. در صورتی که کارفرما از طریق کد، لینک یا معرفی الیت یار وارد الیت‌زون شود، سفارش‌های مرتبط با وی طبق سیاست‌های الیت‌زون به همان الیت یار متصل می‌شود.
۵-۳. الیت یار می‌تواند برای کارفرما پیش‌سفارش ایجاد کند. پیش‌سفارش باید برای تأیید نهایی به کارفرما یا نماینده احرازشده وی ارسال شود.
۵-۴. الیت یار مجاز نیست بدون تأیید کارفرما، سفارش را به نام کارفرما قطعی کند، شرایط خرید را از طرف وی بپذیرد یا پرداخت را نهایی نماید؛ مگر اینکه اختیار مشخص و قابل استناد کارفرما در سامانه یا سند جداگانه ثبت شده باشد.
۵-۵. الیت یار موظف است در معرفی کالاها، صرفاً از اطلاعات معتبر موجود در پلتفرم، اطلاعات رسمی تأمین‌کنندگان و دانش عمومی و حرفه‌ای خود استفاده کند و از ارائه ادعاهای غیرواقعی، قطعی، اغراق‌آمیز یا گمراه‌کننده خودداری نماید.
۵-۶. الیت یار حق ندارد خارج از پلتفرم، از طرف الیت‌زون یا تأمین‌کننده تعهدی ایجاد کند، قیمت قطعی بدهد، تخفیف خارج از سامانه وعده دهد، یا شرایطی برخلاف اطلاعات ثبت‌شده در پلتفرم اعلام نماید.

ماده ۶ — حدود مسئولیت فنی الیت یار
۶-۱. خدمات الیت یار، صرفاً ناظر به راهنمایی، معرفی، مقایسه، آماده‌سازی و پیگیری خرید در پلتفرم الیت‌زون است.
۶-۲. خدمات الیت یار جایگزین طراحی، محاسبه، نظارت، اجرا، کنترل نقشه، آزمایش مصالح، کنترل کیفی رسمی، تأیید فنی پروژه یا خدمات اشخاص دارای صلاحیت قانونی نیست.
۶-۳. مسئولیت انطباق نهایی کالا با نقشه، طراحی، مقررات ملی ساختمان، نظر طراح، ناظر، مجری، محاسب، آزمایشگاه یا سایر مراجع ذی‌صلاح پروژه، بر عهده کارفرما و عوامل فنی ذی‌صلاح وی است.
۶-۴. الیت یار نباید نقش خود در الیت‌زون را به‌عنوان تأیید رسمی فنی، نظارت قانونی، طراحی یا مسئولیت حرفه‌ای پروژه معرفی کند.

ماده ۷ — تعارض منافع و مقررات حرفه‌ای
۷-۱. الیت یار متعهد است در فعالیت خود، کلیه قوانین، مقررات و ضوابط حرفه‌ای مربوط، از جمله مقررات سازمان نظام مهندسی ساختمان، مقررات صنفی، مالیاتی و حرفه‌ای مربوط به فعالیت خود را رعایت کند.
۷-۲. اگر الیت یار در پروژه‌ای دارای سمت رسمی مانند طراح، ناظر، مجری، محاسب، مسئول فنی یا هر عنوان حرفه‌ای مشابه باشد، مسئولیت رعایت مقررات تعارض منافع، اخذ رضایت‌های لازم و خودداری از سوءاستفاده از موقعیت حرفه‌ای بر عهده خود الیت یار است.
۷-۳. الیت یار حق ندارد کارفرما را به خرید از الیت‌زون مجبور کند یا از جایگاه رسمی خود در پروژه برای تحمیل خرید، ایجاد فشار یا القای الزام قانونی استفاده نماید.
۷-۴. الیت یار متعهد است از مهر نظام مهندسی، عنوان رسمی حرفه‌ای، سمت نظارتی یا طراحی خود برای تبلیغ مستقیم کالاها، تأیید فروش یا ایجاد تصور تأیید رسمی کالا استفاده نکند.
۷-۵. الیت یار می‌پذیرد که در صورت تحقق خرید موفق از طریق الیت‌زون، ممکن است از الیت‌زون کارمزد یا حق‌الزحمه دریافت کند و الیت‌زون مجاز است این موضوع را در شرایط استفاده یا فرآیند خرید به کارفرما اعلام نماید.

ماده ۸ — کارمزد، کیف پول و شرایط پرداخت
۸-۱. الیت یار صرفاً در صورتی مستحق کارمزد خواهد بود که سفارش مرتبط با وی در پلتفرم الیت‌زون به خرید موفق منتهی شود.
۸-۲. خرید موفق، حسب سیاست الیت‌زون، می‌تواند شامل تأیید نهایی کارفرما، پرداخت، صدور فاکتور، تحویل کالا، عدم لغو مؤثر، عدم برگشت وجه و نبود اختلاف جدی باشد.
۸-۳. میزان کارمزد الیت یار، نحوه محاسبه، درصد، مبلغ ثابت، پله‌های تشویقی، زمان ثبت در کیف پول و زمان امکان برداشت، طبق سیاست‌های تجاری الیت‌زون و اطلاعات اعلام‌شده در پنل تعیین می‌شود.
۸-۴. الیت‌زون حق دارد سیاست کارمزد را با اعلام در پنل یا انتشار نسخه جدید شرایط، تغییر دهد. تغییرات نسبت به سفارش‌های آتی اعمال می‌شود، مگر آنکه خلاف آن در پنل اعلام شود.
۸-۵. کارمزد الیت یار ابتدا در کیف پول وی ثبت می‌شود. برداشت از کیف پول منوط به احراز هویت، تکمیل مدارک، اعلام حساب بانکی معتبر، نبود اختلاف یا تخلف، رعایت مقررات مالیاتی و صدور فاکتور رسمی یا اسناد مالی مورد قبول الیت‌زون است.
۸-۶. در صورت لغو سفارش، مرجوعی، برگشت وجه، کشف تخلف، سفارش صوری، معرفی فریبنده، دور زدن پلتفرم، نقض محرمانگی یا بروز اختلاف مؤثر، الیت‌زون حق دارد کارمزد را پرداخت نکند، معلق کند، تعدیل نماید یا مبالغ پرداختی را از مطالبات بعدی الیت یار تهاتر کند.
۸-۷. الیت یار مسئول انجام تکالیف مالیاتی و بیمه‌ای مربوط به درآمدهای خود است و الیت‌زون هیچ مسئولیتی نسبت به بدهی‌ها، جرایم یا تعهدات مالیاتی و بیمه‌ای شخص الیت یار ندارد، مگر در حدود تکالیف قانونی مستقیم خود.

ماده ۹ — تعهدات الیت یار
الیت یار متعهد است:
- اطلاعات هویتی، مالی، بانکی، حرفه‌ای و تماس خود را صحیح و به‌روز نگه دارد؛
- از پنل، نام کاربری، رمز عبور، کدها، لینک‌ها و دسترسی‌های خود محافظت کند؛
- صرفاً در چارچوب پلتفرم و ضوابط الیت‌زون فعالیت کند؛
- از ارائه اطلاعات نادرست، گمراه‌کننده یا اغراق‌آمیز به کارفرما خودداری کند؛
- کارفرما را به خرید خارج از الیت‌زون هدایت نکند؛
- اطلاعات کارفرمایان، پروژه‌ها، قیمت‌ها، تأمین‌کنندگان، تخفیف‌ها و سفارش‌ها را محرمانه نگه دارد؛
- از هرگونه تبانی، سفارش صوری، سوءاستفاده از کد معرف، ثبت سفارش نامتعارف یا فریبنده خودداری کند؛
- در صورت بروز خطا، اختلاف، شکایت، تغییر اطلاعات یا مشکل حرفه‌ای، فوراً الیت‌زون را مطلع کند؛
- مقررات نظام مهندسی، صنفی، مالیاتی و حرفه‌ای مربوط به فعالیت خود را رعایت کند؛
- از استفاده از نام، برند، لوگو، محتوا یا داده‌های الیت‌زون خارج از مجوزهای اعلام‌شده خودداری کند.

ماده ۱۰ — تعهدات الیت‌زون
الیت‌زون متعهد است:
- پنل و زیرساخت متعارف لازم برای فعالیت الیت یار را در حدود امکانات پلتفرم فراهم کند؛
- اطلاعات لازم برای استفاده از پنل و رویه‌های همکاری را در اختیار الیت یار قرار دهد؛
- سفارش‌ها، کارمزدها، کیف پول و سوابق مالی مرتبط با الیت یار را در سامانه ثبت و قابل مشاهده کند؛
- کارمزدهای قطعی و قابل پرداخت را طبق سیاست‌های اعلام‌شده و پس از تکمیل شرایط برداشت پرداخت کند؛
- اطلاعات محرمانه الیت یار را در حدود مقررات و سیاست‌های حریم خصوصی حفظ کند؛
- در صورت تخلف، شکایت، نقص مدارک یا ریسک برای پلتفرم، فعالیت الیت یار را محدود، تعلیق یا خاتمه دهد.
الیت‌زون تضمین نمی‌کند که الیت یار به تعداد مشخصی سفارش، درآمد، کارفرما یا فرصت فروش دست یابد.

ماده ۱۱ — محرمانگی و حفاظت از اطلاعات
۱۱-۱. کلیه اطلاعات مربوط به کارفرمایان، پروژه‌ها، سفارش‌ها، قیمت‌ها، تأمین‌کنندگان، تخفیف‌ها، کیف پول‌ها، سوابق خرید، داده‌های پنل، سیاست‌های تجاری و سایر اطلاعاتی که الیت یار در جریان فعالیت در الیت‌زون به آن دسترسی پیدا می‌کند، محرمانه است.
۱۱-۲. الیت یار حق ندارد این اطلاعات را برای رقابت، فروش مستقیم، معرفی به اشخاص ثالث، مذاکره خارج از پلتفرم، تحلیل مستقل تجاری یا هر هدف خارج از اجرای همکاری با الیت‌زون استفاده کند.
۱۱-۳. تعهد محرمانگی از زمان دسترسی به اطلاعات آغاز شده و تا پنج سال پس از خاتمه همکاری معتبر خواهد بود. در مورد اسرار تجاری و اطلاعات مشتریان، این تعهد تا زمانی که اطلاعات عرفاً یا قانوناً محرمانه محسوب شود ادامه خواهد داشت.

ماده ۱۲ — عدم دور زدن پلتفرم
۱۲-۱. الیت یار حق ندارد کارفرما، تأمین‌کننده، پروژه، سفارش یا فرصت تجاری ایجادشده یا شناسایی‌شده از طریق الیت‌زون را خارج از پلتفرم به معامله، مذاکره، خرید، فروش یا همکاری مستقیم هدایت کند.
۱۲-۲. الیت یار حق ندارد با تأمین‌کنندگان الیت‌زون برای سفارش‌ها، پروژه‌ها یا کارفرمایان معرفی‌شده در پلتفرم، خارج از الیت‌زون هماهنگی تجاری انجام دهد.
۱۲-۳. الیت یار حق ندارد کارفرما را تشویق کند که برای دریافت قیمت، تخفیف، حمل، تحویل یا خرید مستقیم، الیت‌زون را دور بزند.
۱۲-۴. در صورت نقض این ماده، الیت‌زون حق دارد حساب الیت یار را تعلیق یا مسدود کند، کارمزدها را پرداخت نکند، مبالغ پرداخت‌شده را مطالبه یا تهاتر نماید، و خسارات وارده را از الیت یار مطالبه کند.
۱۲-۵. وجه التزام نقض عدم دور زدن پلتفرم، معادل ۵ درصد ارزش معامله مستقیم یا غیرمستقیم انجام‌شده خارج از الیت‌زون یا حداقل مبلغ ۵۰۰٬۰۰۰٬۰۰۰ ریال، هرکدام بیشتر باشد، تعیین می‌شود. این وجه التزام مانع مطالبه خسارات مازاد نخواهد بود.

ماده ۱۳ — امنیت پنل و داده‌پیام‌ها
۱۳-۱. کلیه اقدامات انجام‌شده از طریق حساب کاربری، پنل، کد معرف، لینک اختصاصی یا دسترسی‌های الیت یار، منتسب به الیت یار است؛ مگر آنکه الیت یار فوراً سوءاستفاده خارج از اختیار خود را به‌صورت مستند به الیت‌زون اعلام و اثبات کند.
۱۳-۲. تأییدهای الکترونیکی، ورود کد پیامکی، انتخاب گزینه پذیرش، کلیک روی دکمه‌های تأیید، ثبت پیش‌سفارش، درخواست برداشت، پذیرش سیاست کارمزد، پیام‌های پنل و سایر داده‌پیام‌های مرتبط با حساب احرازشده الیت یار، در حدود قوانین لازم‌الاجرا، به‌عنوان سوابق قابل استناد تلقی می‌شود.
۱۳-۳. الیت‌زون مجاز است برای حفظ امنیت، جلوگیری از تقلب، رسیدگی به اختلافات، اجرای قرارداد و رعایت الزامات قانونی، لاگ‌های مربوط به ورود، IP، دستگاه، زمان فعالیت، نسخه قرارداد پذیرفته‌شده، کدهای تأیید و سوابق عملکرد الیت یار را نگهداری کند.

ماده ۱۴ — تعلیق، محدودسازی و خاتمه همکاری
۱۴-۱. الیت‌زون می‌تواند در صورت نقض این توافق‌نامه، نقص مدارک، عدم احراز هویت، شکایت کارفرما، سوءاستفاده از پنل، دور زدن پلتفرم، نقض محرمانگی، سفارش صوری، تعارض منافع حل‌نشده، یا رفتار زیان‌بار برای اعتبار پلتفرم، فعالیت الیت یار را تعلیق، محدود یا خاتمه دهد.
۱۴-۲. الیت یار می‌تواند هر زمان درخواست خاتمه همکاری دهد؛ اما خاتمه همکاری، تعهدات قبلی، محرمانگی، عدم دور زدن، جبران خسارت، تسویه حساب و تعهدات مربوط به سفارش‌های در جریان را از بین نمی‌برد.
۱۴-۳. پس از خاتمه همکاری، کارمزدهای قطعی‌شده و بدون اختلاف، پس از کسر کسورات، خسارات، تعهدات مالیاتی و سایر مبالغ قابل تهاتر، طبق سیاست‌های الیت‌زون قابل تسویه خواهد بود.

ماده ۱۵ — جبران خسارت
در صورت نقض تعهدات این توافق‌نامه توسط الیت یار یا الیت‌زون، طرف متخلف مسئول جبران خسارات مستقیم و قابل اثبات طرف دیگر خواهد بود.
الیت یار در قبال خسارات ناشی از ارائه اطلاعات نادرست، نقض محرمانگی، دور زدن پلتفرم، سوءاستفاده از پنل، جعل اطلاعات، معرفی فریبنده، سفارش صوری، نقض مقررات حرفه‌ای یا تخلف مالیاتی خود مسئول خواهد بود.
الیت‌زون حق دارد خسارات، جرایم، کسورات، مبالغ قابل برگشت یا مطالبات خود را از محل کارمزدها و موجودی کیف پول الیت یار تهاتر کند.

ماده ۱۶ — تغییرات توافق‌نامه
الیت‌زون می‌تواند این توافق‌نامه، سیاست کارمزد، ضوابط پنل، شرایط برداشت، سیاست محرمانگی و سایر مقررات پلتفرم را به‌روزرسانی کند.
نسخه جدید از طریق پنل، پیامک، ایمیل، صفحه توافق‌نامه یا سایر مسیرهای الکترونیکی اعلام می‌شود. ادامه فعالیت الیت یار پس از لازم‌الاجرا شدن نسخه جدید، به منزله پذیرش آن خواهد بود؛ مگر آنکه الیت یار پیش از ادامه فعالیت، همکاری خود را خاتمه دهد.
در مورد تغییرات مهم، الیت‌زون می‌تواند پذیرش مجدد فعال از الیت یار دریافت کند.

ماده ۱۷ — قانون حاکم و حل اختلاف
این توافق‌نامه تابع قوانین جمهوری اسلامی ایران است.
اختلافات ناشی از این توافق‌نامه ابتدا از طریق مذاکره و مکاتبه در پنل یا مسیرهای رسمی الیت‌زون پیگیری می‌شود. در صورت عدم حل اختلاف، موضوع حسب مورد از طریق داوری مورد توافق یا مراجع صالح قانونی پیگیری خواهد شد.

ماده ۱۸ — پذیرش الکترونیکی
الیت یار با انتخاب گزینه پذیرش، ورود کد تأیید، تکمیل ثبت‌نام، استفاده از پنل یا ادامه فعالیت در الیت‌زون، اعلام می‌کند که:
- این توافق‌نامه را مطالعه و درک کرده است؛
- با مفاد آن موافق است؛
- اطلاعات ارائه‌شده توسط وی صحیح است؛
- به‌عنوان شخص مستقل و نه کارمند الیت‌زون فعالیت می‌کند؛
- نقش او صرفاً الیت یار (مشاور همراه خرید) است و جایگزین طراح، ناظر، مجری یا مسئول فنی پروژه نیست؛
- حق دور زدن پلتفرم یا هدایت کارفرما به خرید خارج از الیت‌زون را ندارد؛
- کارمزد وی فقط طبق سیاست الیت‌زون و پس از تحقق شرایط پرداخت قابل مطالبه است؛
- مسئول رعایت مقررات حرفه‌ای، مالیاتی، بیمه‌ای و تعارض منافع مربوط به خود است.
