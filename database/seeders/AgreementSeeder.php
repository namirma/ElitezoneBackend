            ['code' => 'CHK-04', 'text' => 'متعهد می‌شوم کارفرما، پروژه، سفارش یا تأمین‌کننده را به خرید یا معامله خارج از الیت‌زون هدایت نکنم.'],
            ['code' => 'CHK-05', 'text' => 'متعهد می‌شوم اطلاعات کارفرمایان، پروژه‌ها، قیمت‌ها، سفارش‌ها، تخفیف‌ها و داده‌های پلتفرم را محرمانه نگه دارم.'],
            ['code' => 'CHK-06', 'text' => 'می‌پذیرم کارمزد من فقط طبق سیاست الیت‌زون، پس از تحقق خرید موفق، ثبت در کیف پول، تکمیل مدارک و رعایت الزامات مالیاتی قابل پرداخت یا برداشت است.'],
