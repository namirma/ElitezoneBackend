 *   3. توافق‌نامه الیت یار              — elite_yar_terms  ← متن کامل مصوب (docx v1.0)
 *   4. توافق‌نامه کارفرما               — employer_terms
 *   5. توافق‌نامه سوپلایر               — supplier_terms
 *
 * idempotent: بر اساس (slug, version) — اجرای مجدد seeder نسخه موجود را دست
 * نمی‌زند (متن نسخه‌ی منتشرشده هرگز نباید تغییر کند؛ اصلاح یعنی نسخه‌ی جدید).
 *
 * متن الیت یار از سند رسمی «توافقنامه آنلاین مشاور الیت زون — دستورالعمل
 * پیاده‌سازی» (نسخه ۱.۰) وارد شده؛ نام‌گذاری محصول «الیت یار» است (معادل
 * «مشاور همراه خرید» در متن حقوقی).
 */
class AgreementSeeder extends Seeder
{
    public function run(): void
    {
        $this->seedAgreement(
            slug: Agreement::SLUG_ELITE_YAR_TERMS,
            title: 'توافق‌نامه همکاری الیت یار (مشاور همراه خرید) الیت‌زون',
            version: '1.0',
            content: $this->eliteYARTermsContent(),
            checkboxes: $this->eliteYARCheckboxes(),
        );

        $this->seedAgreement(
            slug: Agreement::SLUG_ELITEZONE_TERMS,
            title: 'شرایط استفاده از الیت‌زون',
            version: '1.0',
            content: $this->placeholderContent('شرایط استفاده از پلتفرم الیت‌زون'),
        );

        $this->seedAgreement(
            slug: Agreement::SLUG_PRIVACY_POLICY,
            title: 'قوانین حریم خصوصی الیت‌زون',
            version: '1.0',
            content: $this->placeholderContent('قوانین حریم خصوصی پلتفرم الیت‌زون'),
        );

        $this->seedAgreement(
            slug: Agreement::SLUG_EMPLOYER_TERMS,
            title: 'توافق‌نامه کارفرمای الیت‌زون',
            version: '1.0',
            content: $this->placeholderContent('توافق‌نامه اختصاصی کارفرما در پلتفرم الیت‌زون'),
        );

        $this->seedAgreement(
            slug: Agreement::SLUG_SUPPLIER_TERMS,
            title: 'توافق‌نامه سوپلایر الیت‌زون',
            version: '1.0',
            content: $this->placeholderContent('توافق‌نامه اختصاصی سوپلایر در پلتفرم الیت‌زون'),
        );
    }

    private function seedAgreement(
        string $slug,
        string $title,
        string $version,
        string $content,
        ?array $checkboxes = null,
    ): void {
        Agreement::firstOrCreate(
            [Agreement::SLUG => $slug, Agreement::VERSION => $version],
            [
                Agreement::TITLE => $title,
                Agreement::CONTENT => $content,
                Agreement::CHECKBOXES => $checkboxes,
                Agreement::CONTENT_SHA256 => hash('sha256', $content),
                Agreement::EFFECTIVE_AT => now(),
                Agreement::IS_ACTIVE => true,
                Agreement::IS_MANDATORY => true,
            ],
        );
    }

    /**
     * متن‌های عمومی/نقشی که هنوز متن حقوقی نهایی ندارند — نسخه اولیه.
     * وقتی واحد حقوقی متن نهایی را داد، نسخه‌ی جدید (2.0) اضافه کنید؛
     * این نسخه را ویرایش نکنید.
     */
    private function placeholderContent(string $subject): string
    {
        return "{$subject}\n\n".
            'این سند چارچوب کلی استفاده از پلتفرم الیت‌زون (متعلق به شرکت نرم‌افزاری سازه اسپادانا، elitezone.me) را تعیین می‌کند. '.
            'کاربر با پذیرش این سند اعلام می‌کند اطلاعات ارائه‌شده توسط وی صحیح است، قوانین جمهوری اسلامی ایران و ضوابط پلتفرم را رعایت می‌کند، '.
            "و می‌پذیرد تأییدهای الکترونیکی و سوابق فعالیت وی در سامانه در حدود قوانین لازم‌الاجرا به‌عنوان داده‌پیام قابل استناد تلقی شود.\n\n".
            '(نسخه اولیه — متن تفصیلی این سند پس از تأیید مشاور حقوقی شرکت در قالب نسخه جدید منتشر می‌شود.)';
    }

