    {
        foreach ($this->home() as $i => $block) {
            $this->put(PageBlock::PAGE_HOME, $i + 1, $block);
        }
    }

    private function put(string $page, int $order, array $block): void
    {
        PageBlock::firstOrCreate(
            [PageBlock::PAGE => $page, PageBlock::SORT_ORDER => $order],
            [PageBlock::TYPE => $block['type'], PageBlock::DATA => $block['data'], PageBlock::IS_ACTIVE => true],
        );
    }

