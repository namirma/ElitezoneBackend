    /** پیشوندِ مسیرِ هر عکسی که این سیدر به آن اشاره می‌کند (دیسکِ public). */
    public const MEDIA_PREFIX = 'page-blocks/v276/';

    public function run(): void
    {
        foreach ($this->home() as $i => $block) {
            $this->put(PageBlock::PAGE_HOME, $i + 1, $block);
        }

        foreach ($this->podium() as $i => $block) {
            $this->put(PageBlock::PAGE_PODIUM, $i + 1, $block);
        }

        foreach ($this->steelKavir() as $i => $block) {
            $this->put(PageBlock::PAGE_STEEL_KAVIR, $i + 1, $block);
        }
    }

    private function put(string $page, int $order, array $block): void
    {
        PageBlock::firstOrCreate(
            [PageBlock::PAGE => $page, PageBlock::SORT_ORDER => $order],
            [PageBlock::TYPE => $block['type'], PageBlock::DATA => $block['data'], PageBlock::IS_ACTIVE => true],
        );
    }

