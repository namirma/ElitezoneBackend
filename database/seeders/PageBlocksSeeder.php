     * هر عکسی که بلوک‌های سیدشده به آن اشاره می‌کنند، یک‌بار — ورودیِ `page-blocks:import-media`.
     *
     * @return list<string>
     */
    public static function mediaPaths(): array
    {
        $seeder = new self;
        $paths = [];
        $blocks = [$seeder->home(), $seeder->podium(), $seeder->steelKavir()];
        array_walk_recursive(
            $blocks,
            function ($value) use (&$paths) {
                if (is_string($value) && str_starts_with($value, self::MEDIA_PREFIX)) {
                    $paths[$value] = true;
                }
            }
        );

        return array_keys($paths);
    }

